export function uiText(language: UiLanguage, text: string, values: Record<string, string | number> = {}): string {
  const normalized = text.replace(/\s+/g, " ").trim();
  const template = language === "zh-CN" ? chinese[normalized] ?? normalized : normalized;
  return template.replace(/\{(\w+)\}/g, (match, key: string) => String(values[key] ?? match));
}

export function readUiLanguage(storage: Pick<Storage, "getItem">): UiLanguage {
  try { return storage.getItem(LANGUAGE_KEY) === "zh-CN" ? "zh-CN" : "en"; }
  catch { return "en"; }
}

export function localizeNotice(language: UiLanguage, text: string): string {
  if (language === "en") return text;
  const shot = /^Shot (\d+): shorten the caption to three lines\.$/.exec(text);
  if (shot) return `镜头 ${shot[1]}：请将文案缩短到三行以内。`;
  const restore = /^Restore version (\d+) as a new draft\?/.exec(text);
  if (restore) return uiText(language, "Restore version {number} as a new draft? This replaces the current storyboard, including its locks. Saved versions remain intact.", { number: restore[1] });
  return uiText(language, text);
}

